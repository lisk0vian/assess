// Package proctor turns browser integrity signals into decisions: a warning,
// a strike, lost time or a voided question. Decisions follow the exam's
// profile and are always reversible by the teacher.
//
// standard and strict protect the same way (pledge, curtain, copy and paste
// blocked, capture shield, watermark, required fullscreen, hover-only
// options, and against photos: a prompt read in ranges of words and a
// stillness warning); they differ in tolerance. standard ignores short glances, warns
// before counting and annuls at 3 strikes. strict counts almost everything
// at once and annuls at the second strike: the first one is the warning.
// off turns every protection off.
package proctor

import "time"

// Signal kinds reported by the browser.
const (
	Hidden         = "hidden"          // the exam tab was hidden for DurationMs
	Blur           = "blur"            // the window lost focus while visible for DurationMs
	Copy           = "copy"            // copy or cut on the exam (right-click is only blocked)
	Screenshot     = "screenshot"      // PrintScreen, or trying to print the exam
	PasteInput     = "paste_input"     // text pasted, dropped or inserted by an extension into an answer
	Burst          = "burst"           // text appeared faster than anyone types
	FullscreenExit = "fullscreen_exit" // left fullscreen for DurationMs (required mode)
	Untrusted      = "untrusted"       // a click or key generated by a script (event.isTrusted === false)
	Webdriver      = "webdriver"       // the browser is driven by automation
	DOMInjection   = "dom_injection"   // an extension injected elements into the page
	Resize         = "resize"          // the window shrank abruptly (split screen)
	SecondTab      = "second_tab"      // the exam was opened in another tab
	Telemetry      = "telemetry"       // signed telemetry failed verification
	TelemetryGap   = "telemetry_gap"   // answers arrived while the live channel was silent
	FrozenPointer  = "frozen_pointer"  // no pointer or key activity for DurationMs on an open question
)

// Severity of a decision, mirrored in events.
type Severity string

// Severities.
const (
	Info Severity = "info"
	Warn Severity = "warn"
	High Severity = "high"
)

// Decision is what to do with one signal.
type Decision struct {
	Severity  Severity
	Warn      bool    // tell the student (non-blocking notice)
	Strike    bool    // count a strike
	LoseShare float64 // share of the attempt's remaining time to remove (0.2 = 20 %)
	VoidQ     bool    // the current question scores 0 and closes
	Ignore    bool    // below thresholds: record nothing
}

// Signal is one report, enriched with how many times this kind happened
// before in the attempt (Count starts at 1).
type Signal struct {
	Kind       string
	DurationMs int64
	Count      int
}

// Settings are the effective proctoring options of an exam.
type Settings struct {
	Profile     string // off | standard | strict
	Fullscreen  string // off | suggested | required
	Devices     string // any | desktop
	Reveal      string // always | hover (default for questions)
	StrikeLimit int
	// Grace ignores signals right after the start (page load, fullscreen prompt).
	Grace time.Duration
	// Against photos of the screen, each one switchable on its own.
	Lens          bool   // the prompt is read in ranges of words, one at a time
	FrozenPointer bool   // report a still pointer followed by an answer
	AutoRead      bool   // read the prompt once when it opens
	ReadSpeed     string // slow | normal | fast
}

// Read speeds, used by the student's reading guide.
const (
	ReadSlow   = "slow"
	ReadNormal = "normal"
	ReadFast   = "fast"
)

// Resolve applies a profile's defaults under explicit manifest choices. With
// off, nothing is protected and the overrides are ignored.
func Resolve(profile, fullscreen, devices, reveal string, strikeLimit int) Settings {
	s := Settings{Profile: profile, Fullscreen: "required", Devices: "any", Reveal: "hover", StrikeLimit: 3, Grace: 15 * time.Second,
		Lens: true, FrozenPointer: true, AutoRead: true, ReadSpeed: ReadNormal}
	switch profile {
	case "off":
		return Settings{Profile: "off", Fullscreen: "off", Devices: "any", Reveal: "always"}
	case "strict":
		s.Devices, s.StrikeLimit = "desktop", 2
	default:
		s.Profile = "standard"
	}
	if fullscreen != "" {
		s.Fullscreen = fullscreen
	}
	if devices != "" {
		s.Devices = devices
	}
	if reveal != "" {
		s.Reveal = reveal
	}
	if strikeLimit > 0 {
		s.StrikeLimit = strikeLimit
	}
	return s
}

// AntiPhoto applies the manifest's choices for the photo protections; nil
// keeps the profile's default. With off they stay off.
func (s Settings) AntiPhoto(lens, frozenPointer *bool) Settings {
	if !s.Enabled() {
		return s
	}
	if lens != nil {
		s.Lens = *lens
	}
	if frozenPointer != nil {
		s.FrozenPointer = *frozenPointer
	}
	return s
}

// Reading applies the manifest's reading settings. Auto read only makes sense
// with the lens; an unknown speed keeps the profile's default.
func (s Settings) Reading(autoRead *bool, speed string) Settings {
	if !s.Enabled() {
		return s
	}
	if autoRead != nil {
		s.AutoRead = *autoRead
	}
	switch speed {
	case ReadSlow, ReadNormal, ReadFast:
		s.ReadSpeed = speed
	}
	return s
}

// LoseShare is the share of the remaining time a long absence costs:
// 20 % in standard, half of it in strict.
func (s Settings) LoseShare() float64 {
	if s.Profile == "strict" {
		return 0.5
	}
	return 0.2
}

// Enabled reports whether signals are collected at all.
func (s Settings) Enabled() bool { return s.Profile != "off" }

// Decide maps a signal to a decision under these settings.
func (s Settings) Decide(sig Signal) Decision {
	if !s.Enabled() {
		return Decision{Ignore: true}
	}
	strict := s.Profile == "strict"
	th := s.Thresholds()
	d := sig.DurationMs
	// strict: every offence counts at once. standard: the first copy, capture
	// or paste is a warning, later ones count.
	first := !strict && sig.Count <= 1
	strike := Decision{Severity: High, Warn: true, Strike: true}
	switch sig.Kind {
	case Hidden, Blur:
		lo, hi := th.HiddenWarn, th.HiddenStrike
		if sig.Kind == Blur {
			lo, hi = th.BlurWarn, th.BlurStrike
		}
		switch {
		case d < lo:
			return Decision{Ignore: true}
		case d <= hi:
			return Decision{Severity: Warn, Warn: true}
		case sig.Kind == Hidden:
			strike.LoseShare = s.LoseShare()
		}
		return strike
	case Copy, Screenshot:
		if first {
			return Decision{Severity: Warn, Warn: true}
		}
		strike.VoidQ = true
		return strike
	case PasteInput:
		if first {
			return Decision{Severity: Warn, Warn: true}
		}
		return strike
	case FullscreenExit:
		if s.Fullscreen != "required" {
			return Decision{Severity: Info}
		}
		if d > th.FullscreenStrike {
			return strike
		}
		return Decision{Severity: Warn}
	case Untrusted, Webdriver, Telemetry:
		return strike
	case Burst, DOMInjection, SecondTab, TelemetryGap:
		return Decision{Severity: Warn}
	case FrozenPointer:
		// Only for the teacher: reading without moving is normal too.
		if !s.FrozenPointer || d < th.Frozen {
			return Decision{Ignore: true}
		}
		return Decision{Severity: Warn}
	}
	return Decision{Severity: Info}
}

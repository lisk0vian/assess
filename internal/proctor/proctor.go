// Package proctor turns browser integrity signals into decisions: a warning,
// a strike, lost time or a voided question. Decisions follow the exam's
// profile (off, standard, strict) and are always reversible by the teacher.
package proctor

import "time"

// Signal kinds reported by the browser.
const (
	Hidden         = "hidden"          // the exam tab was hidden for DurationMs
	Blur           = "blur"            // the window lost focus while visible for DurationMs
	Copy           = "copy"            // copy or cut on the exam (right-click is only blocked)
	Screenshot     = "screenshot"      // PrintScreen, or trying to print the exam
	PasteInput     = "paste_input"     // text pasted, dropped or inserted by an extension into an answer
	Burst          = "burst"           // text appeared faster than anyone types
	FullscreenExit = "fullscreen_exit" // left fullscreen for DurationMs (required mode)
	Untrusted      = "untrusted"       // a click or key generated by a script (event.isTrusted === false)
	Webdriver      = "webdriver"       // the browser is driven by automation
	DOMInjection   = "dom_injection"   // an extension injected elements into the page
	Resize         = "resize"          // the window shrank abruptly (split screen)
	SecondTab      = "second_tab"      // the exam was opened in another tab
	Telemetry      = "telemetry"       // signed telemetry failed verification
	TelemetryGap   = "telemetry_gap"   // answers arrived while the live channel was silent
)

// Severity of a decision, mirrored in events.
type Severity string

// Severities.
const (
	Info Severity = "info"
	Warn Severity = "warn"
	High Severity = "high"
)

// Decision is what to do with one signal.
type Decision struct {
	Severity Severity
	Warn     bool          // tell the student (non-blocking notice)
	Strike   bool          // count a strike
	LoseTime time.Duration // remove time from the attempt
	VoidQ    bool          // the current question scores 0 and closes
	Ignore   bool          // below thresholds: record nothing
}

// Signal is one report, enriched with how many times this kind happened
// before in the attempt (Count starts at 1).
type Signal struct {
	Kind       string
	DurationMs int64
	Count      int
}

// Settings are the effective proctoring options of an exam.
type Settings struct {
	Profile     string // off | standard | strict
	Fullscreen  string // off | suggested | required
	Devices     string // any | desktop
	Reveal      string // always | hover (default for questions)
	StrikeLimit int
	// Grace ignores signals right after the start (page load, fullscreen prompt).
	Grace time.Duration
}

// Resolve applies a profile's defaults under explicit manifest choices.
func Resolve(profile, fullscreen, devices, reveal string, strikeLimit int) Settings {
	s := Settings{Profile: profile, Fullscreen: "suggested", Devices: "any", Reveal: "always", StrikeLimit: 3, Grace: 15 * time.Second}
	switch profile {
	case "off":
		s.Fullscreen, s.StrikeLimit = "off", 0
	case "strict":
		s.Fullscreen, s.Devices, s.Reveal = "required", "desktop", "hover"
	default:
		s.Profile = "standard"
	}
	if fullscreen != "" {
		s.Fullscreen = fullscreen
	}
	if devices != "" {
		s.Devices = devices
	}
	if reveal != "" {
		s.Reveal = reveal
	}
	if strikeLimit > 0 {
		s.StrikeLimit = strikeLimit
	}
	return s
}

// Enabled reports whether signals are collected at all.
func (s Settings) Enabled() bool { return s.Profile != "off" }

// Decide maps a signal to a decision under these settings.
func (s Settings) Decide(sig Signal) Decision {
	if !s.Enabled() {
		return Decision{Ignore: true}
	}
	strict := s.Profile == "strict"
	th := s.Thresholds()
	d := sig.DurationMs
	pick := func(strictD, standardD Decision) Decision {
		if strict {
			return strictD
		}
		return standardD
	}
	switch sig.Kind {
	case Hidden:
		lo, hi := th.HiddenWarn, th.HiddenStrike
		switch {
		case d < lo:
			return Decision{Ignore: true}
		case d <= hi:
			return Decision{Severity: Warn, Warn: true}
		default:
			out := Decision{Severity: High, Warn: true, Strike: true}
			if strict {
				out.LoseTime = time.Minute
			}
			return out
		}
	case Blur:
		lo, hi := th.BlurWarn, th.BlurStrike
		switch {
		case d < lo:
			return Decision{Ignore: true}
		case d <= hi:
			return Decision{Severity: Warn, Warn: true}
		default:
			return Decision{Severity: High, Warn: true, Strike: true}
		}
	case Copy, Screenshot:
		if sig.Count <= 1 {
			return pick(Decision{Severity: High, Warn: true, Strike: true}, Decision{Severity: Warn, Warn: true})
		}
		return pick(Decision{Severity: High, Warn: true, Strike: true, VoidQ: true}, Decision{Severity: High, Warn: true, Strike: true})
	case PasteInput:
		return pick(Decision{Severity: High, Warn: true, Strike: true}, Decision{Severity: Warn, Warn: true})
	case FullscreenExit:
		if s.Fullscreen != "required" {
			return Decision{Severity: Info}
		}
		if d > th.FullscreenStrike {
			return Decision{Severity: High, Warn: true, Strike: true}
		}
		return Decision{Severity: Warn}
	case Untrusted, Webdriver, Telemetry:
		return Decision{Severity: High, Warn: true, Strike: true}
	case Burst, DOMInjection, SecondTab, TelemetryGap:
		return Decision{Severity: Warn}
	case Resize:
		return Decision{Severity: Info}
	}
	return Decision{Severity: Info}
}

// Generates src/i18n.keys.ts from the web section of locales/en.yaml, so
// t("...") calls are checked by TypeScript. The texts themselves are not
// bundled: the server injects the exam language's catalog into the page.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const yaml = readFileSync(join(here, "..", "..", "locales", "en.yaml"), "utf8");

const keys = [];
let inWeb = false;
for (const line of yaml.split(/\r?\n/)) {
  if (/^\S/.test(line)) inWeb = line.startsWith("web:");
  const m = inWeb && line.match(/^  ([a-z0-9_]+):/);
  if (m) keys.push(m[1]);
}
if (keys.length < 50) throw new Error(`only ${keys.length} web keys found in locales/en.yaml`);

const out =
  "// Generated by scripts/keys.mjs from locales/en.yaml. Do not edit.\n" +
  "export type Key =\n" +
  keys.map((k) => `  | ${JSON.stringify(k)}`).join("\n") +
  ";\n";
writeFileSync(join(here, "..", "src", "i18n.keys.ts"), out);

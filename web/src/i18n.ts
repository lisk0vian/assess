const dicts: Record<string, Dict> = { es, en };

let current: Dict = navigator.language.startsWith("en") ? en : es;

export function setLanguage(lang: string): void {
  current = dicts[lang] ?? es;
  document.documentElement.lang = lang in dicts ? lang : "es";
}

/** t looks up a string and fills {placeholders}. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return current[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
}

export function points(n: number): string {
  const v = Number.isInteger(n) ? String(n) : n.toLocaleString(document.documentElement.lang, { maximumFractionDigits: 2 });
  return t(n === 1 ? "pts_one" : "pts_many", { n: v });
}
